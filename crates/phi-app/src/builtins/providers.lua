-- The first-party provider catalog, registered through the same public
-- `phi.register_provider` door user extensions use (DESIGN.md, The Rule:
-- built-ins are extensions). This file *is* the model catalog -- there is
-- no embedded models.json; `Registry::builtin()` carries only the API
-- protocol implementations (anthropic-messages, openai-responses,
-- openai-completions, cursor-native) and every model grafts on here.
--
-- Auth is not declared here: OAuth flows (anthropic, openai, cursor) are
-- native, and API keys resolve from stored credentials or the generic
-- {PROVIDER}_API_KEY env fallback (e.g. NEURALWATT_API_KEY). Re-registering
-- a provider name replaces it, so a user extension can override any of
-- these (e.g. to route through a proxy) without forking this file.

